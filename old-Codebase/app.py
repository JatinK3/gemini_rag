def sanitize_filename(filename: str) -> str:
    base = Path(filename).name
    safe = re.sub(r"[^A-Za-z0-9._-]", "_", base)
    return safe or f"upload_{int(time.time())}"

def safe_write_tmp(data: bytes, original_name: str) -> str:
    safe_name = sanitize_filename(original_name)
    tmp_dir = tempfile.gettempdir()
    tmp_path = os.path.abspath(os.path.join(tmp_dir, f"{int(time.time())}_{safe_name}"))
    with open(tmp_path, "wb") as out:
        out.write(data)
    return tmp_path

def robust_upload_to_store(client, tmp_path, store_name, config, sidebar_status):
    """
    Try several upload modes (path string, file handle, bytes-io).
    Returns operation object (or raises).
    sidebar_status: dict-like with 'text' and 'progress' callables to update UI in sidebar
    """
    upload_exceptions = []
    op = None

    # Mode 1: path string
    try:
        sidebar_status["text"]("Starting upload (path mode)...")
        op = client.file_search_stores.upload_to_file_search_store(
            file=tmp_path,
            file_search_store_name=store_name,
            config=config
        )
        sidebar_status["text"]("Upload started (path mode).")
    except Exception as e_path:
        upload_exceptions.append(("path", e_path))
        sidebar_status["text"](f"Path upload failed: {e_path}")

    # Mode 2: file handle
    if op is None:
        try:
            sidebar_status["text"]("Trying upload (file-handle mode)...")
            with open(tmp_path, "rb") as fh:
                op = client.file_search_stores.upload_to_file_search_store(
                    file=fh,
                    file_search_store_name=store_name,
                    config=config
                )
            sidebar_status["text"]("Upload started (file-handle mode).")
        except Exception as e_fh:
            upload_exceptions.append(("file_handle", e_fh))
            sidebar_status["text"](f"File-handle upload failed: {e_fh}")

    # Mode 3: BytesIO
    if op is None:
        try:
            sidebar_status["text"]("Trying upload (bytes-io mode)...")
            with open(tmp_path, "rb") as f:
                data = f.read()
            bio = io.BytesIO(data)
            bio.name = Path(tmp_path).name
            op = client.file_search_stores.upload_to_file_search_store(
                file=bio,
                file_search_store_name=store_name,
                config=config
            )
            sidebar_status["text"]("Upload started (bytes-io mode).")
        except Exception as e_bio:
            upload_exceptions.append(("bytes_io", e_bio))
            # All modes failed -> raise with diagnostics
            msg_lines = ["All upload modes failed. Exceptions:"]
            for mode, ex in upload_exceptions:
                msg_lines.append(f"- {mode}: {ex}")
            msg = "\n".join(msg_lines)
            raise RuntimeError(msg)

    return op

def poll_operation(client, op, sidebar_status, timeout=300, interval=2):
    """
    Poll an operation until done or timeout. Updates sidebar_status progress.
    Returns the final op object or last-known op info when timeout reached.
    """
    waited = 0
    sidebar_status["text"]("Polling import status...")
    max_steps = max(1, timeout // max(1, interval))
    step = 0

    # attempt to get a stable operation name/identifier if present
    op_name = None
    try:
        # Many SDK operation objects have .name or .operation_name
        op_name = getattr(op, "name", None) or getattr(op, "operation_name", None)
        # if op is a dict or has .to_dict() with 'name':
        if op_name is None:
            if isinstance(op, dict):
                op_name = op.get("name")
            else:
                try:
                    od = getattr(op, "to_dict", lambda: None)()
                    if isinstance(od, dict):
                        op_name = od.get("name")
                except Exception:
                    pass
    except Exception:
        op_name = None

    while waited < timeout:
        # update progress heuristic
        pct = min(100, int((step / max_steps) * 100))
        try:
            sidebar_status["progress"](pct)
        except Exception:
            pass

        # check a simple 'done' attribute first
        done = getattr(op, "done", None)
        if done is True:
            sidebar_status["text"]("Import operation completed.")
            break

        # attempt a refresh if we have a client.operations.get and an op_name
        try:
            if op_name:
                refreshed = client.operations.get(op_name)
                if refreshed is not None:
                    op = refreshed
            else:
                # if operations.get accepts operation object or name, try both safely
                try:
                    refreshed = client.operations.get(op)
                    if refreshed is not None:
                        op = refreshed
                except Exception:
                    pass
        except Exception:
            # ignore refresh errors; continue polling
            pass

        if getattr(op, "done", False) is True:
            sidebar_status["text"]("Import operation completed (after refresh).")
            break

        time.sleep(interval)
        waited += interval
        step += 1

    if getattr(op, "done", False) is not True:
        sidebar_status["text"]("Import timed out or still running.")
    # final progress set to 100 if done else leave as-is
    try:
        if getattr(op, "done", False):
            sidebar_status
    except Exception:
        pass

    return op


def _find_in_obj(obj, keys):
    """Recursively search obj (dict/list) for the first value matching any key in `keys` (case-insensitive)."""
    if obj is None:
        return None
    if isinstance(obj, dict):
        for k, v in obj.items():
            if any(k.lower() == kk for kk in keys):
                return v
        # deeper search
        for k, v in obj.items():
            res = _find_in_obj(v, keys)
            if res is not None:
                return res
    elif isinstance(obj, list):
        for el in obj:
            res = _find_in_obj(el, keys)
            if res is not None:
                return res
    return None

def _guess_doc_name_from_response(resp):
    raw = getattr(resp, "_raw", None) or getattr(resp, "raw", None)
    if not isinstance(raw, dict):
        return None

    candidates = {}

    def walk(u):
        if isinstance(u, dict):
            # if a dict contains both id-like and name-like keys, map them
            id_key = None
            name_key = None
            for k in u.keys():
                kl = k.lower()
                if "id" in kl and ("file" in kl or "doc" in kl or "chunk" in kl or "name" in kl):
                    id_key = k
                if "name" in kl or "file" in kl or "display" in kl or "title" in kl:
                    name_key = k
            if id_key and name_key and isinstance(u.get(id_key), (str,int)) and isinstance(u.get(name_key), str):
                candidates[str(u.get(id_key))] = u.get(name_key)
            # also map direct file dicts
            if "file_name" in u and isinstance(u.get("file_name"), str):
                candidates[u.get("file_name")] = u.get("file_name")
            if "document_name" in u and isinstance(u.get("document_name"), str):
                candidates[u.get("document_name")] = u.get("document_name")
            # recursive
            for v in u.values():
                walk(v)
        elif isinstance(u, list):
            for el in u:
                walk(el)

    walk(raw)
    return candidates or None


def _normalize_chunk(ch, resp_for_lookup=None):
    text = None
    doc = None
    start = None
    end = None
    score = None

    # Try to convert SDK objects to dict-like
    try:
        if hasattr(ch, "to_dict"):
            ch = ch.to_dict()
        elif hasattr(ch, "dict"):
            ch = ch.dict()
    except Exception:
        pass

    # If it's a dict, inspect expected fields
    if isinstance(ch, dict):
        # 1) Common nested containers that hold text and doc
        for container_key in (
            "retrieved_context", "retrieved_contexts", "segment",
            "retrieval_segment", "rag_chunk", "retrieval", "content"
        ):
            if container_key in ch and isinstance(ch[container_key], dict):
                seg = ch[container_key]
                text = text or seg.get("text") or seg.get("rag_chunk") or seg.get("content")
                doc = doc or seg.get("document_name") or seg.get("file_name") or seg.get("document") or seg.get("source")
                start = start or seg.get("start_index") or seg.get("start")
                end = end or seg.get("end_index") or seg.get("end")

        # 2) Top-level text fields
        if text is None:
            text = ch.get("text") or ch.get("rag_chunk") or ch.get("chunk_text") or ch.get("retrieved_text") or ch.get("content")

        # 3) Top-level doc-like fields (look for many possible keys)
        doc = doc or ch.get("document_name") or ch.get("file_name") or ch.get("document") or ch.get("source") or ch.get("file")

        # 4) Score fields
        score = ch.get("score") or ch.get("confidence") or ch.get("confidence_score")

        # 5) start/end at top-level if present
        if start is None:
            start = ch.get("start_index") or ch.get("start")
        if end is None:
            end = ch.get("end_index") or ch.get("end")

        # 6) NEW: check for common "title"/"display_name"/"name" keys on chunk itself
        if doc is None:
            for key in ("title", "display_name", "name"):
                val = ch.get(key)
                if isinstance(val, str) and val.strip():
                    doc = val.strip()
                    break

        # 7) NEW: if still missing, check inside retrieved_context (if present) for title/display_name
        if doc is None:
            rc = ch.get("retrieved_context") or ch.get("retrieved_contexts") or ch.get("segment") or None
            if isinstance(rc, dict):
                for key in ("title", "display_name", "document_name", "file_name", "file"):
                    val = rc.get(key)
                    if isinstance(val, str) and val.strip():
                        doc = val.strip()
                        break

    else:
        # fallback: stringify
        text = str(ch)

    # If doc still missing, try to find mapping in the full response (e.g., id->name)
    if doc is None and resp_for_lookup is not None:
        mapping = _guess_doc_name_from_response(resp_for_lookup)
        # sometimes chunk contains an id field pointing to actual file - search for id-like keys
        id_candidate = _find_in_obj(ch, ["document_id", "file_id", "id", "documentId", "fileId", "chunk_id", "file_name"])
        if id_candidate:
            key = str(id_candidate)
            if mapping and key in mapping:
                doc = mapping[key]
        # if mapping contains any filename-like strings, pick the first as a last resort
        if doc is None and mapping:
            for k, v in mapping.items():
                if isinstance(k, str) and any(ext in k.lower() for ext in (".pdf", ".txt", ".doc", ".docx", ".md")):
                    doc = v or k
                    break
            if doc is None:
                for v in mapping.values():
                    doc = v
                    break

    # Final normalization
    text = (text or "").strip() if text is not None else None
    doc = doc or None
    return {"text": text, "doc": doc, "start": start, "end": end, "score": score}



def get_top_grounding_snippets(resp, top_n=3):
    """
    Return up to top_n normalized grounding snippets. Uses candidate-level grounding first,
    then top-level attributes, then raw fallback. Tries to discover document names.
    """
    snippets = []

    # candidate-level grounding (common)
    try:
        cand_list = getattr(resp, "candidates", None)
        if cand_list and len(cand_list) > 0:
            cand = cand_list[0]
            # try known names
            gm = (getattr(cand, "grounding_metadata", None)
                  or getattr(cand, "groundingMetadata", None)
                  or getattr(cand, "grounding", None)
                  or getattr(cand, "grounding_chunks", None)
                  or getattr(cand, "retrievals", None)
                  or getattr(cand, "sources", None))
            # try to normalize gm to dict/list
            try:
                if hasattr(gm, "to_dict"):
                    gm = gm.to_dict()
                elif hasattr(gm, "dict"):
                    gm = gm.dict()
            except Exception:
                pass

            if isinstance(gm, dict):
                # prioritize grounding_chunks or retrieved_chunks
                chunks = gm.get("grounding_chunks") or gm.get("retrieved_chunks") or gm.get("chunks") or gm.get("items")
                if isinstance(chunks, (list, tuple)):
                    for ch in chunks:
                        snippets.append(_normalize_chunk(ch, resp_for_lookup=resp))
            # supports/grounding_supports sometimes contain segments
            supports = None
            if isinstance(gm, dict):
                supports = gm.get("grounding_supports") or gm.get("groundingSupports") or gm.get("supports")
            if isinstance(supports, (list, tuple)):
                for s in supports:
                    seg = None
                    if isinstance(s, dict):
                        seg = s.get("segment") or s.get("retrieved_segment")
                    if seg:
                        snippets.append(_normalize_chunk(seg, resp_for_lookup=resp))
    except Exception:
        pass

    # top-level grounding attributes
    if len(snippets) < top_n:
        for attr in ("grounding_metadata", "grounding", "grounding_chunks", "retrievals", "sources", "citation_metadata"):
            val = getattr(resp, attr, None)
            if val:
                try:
                    if hasattr(val, "to_dict"):
                        val = val.to_dict()
                    elif hasattr(val, "dict"):
                        val = val.dict()
                except Exception:
                    pass
                if isinstance(val, dict):
                    chunks = val.get("grounding_chunks") or val.get("retrieved_chunks") or val.get("chunks") or val.get("items")
                    if isinstance(chunks, (list, tuple)):
                        for ch in chunks:
                            snippets.append(_normalize_chunk(ch, resp_for_lookup=resp))
                elif isinstance(val, (list, tuple)):
                    for el in val:
                        snippets.append(_normalize_chunk(el, resp_for_lookup=resp))

    # raw fallback search
    if len(snippets) < top_n:
        raw = getattr(resp, "_raw", None) or getattr(resp, "raw", None)
        def scan_for_chunks(obj):
            found = []
            if isinstance(obj, dict):
                for k, v in obj.items():
                    lk = k.lower()
                    if lk in ("grounding_chunks","retrieved_chunks","chunks","grounding","retrievals","sources","items"):
                        if isinstance(v, (list, tuple)):
                            for el in v:
                                found.append(el)
                        else:
                            found.append(v)
                    else:
                        found += scan_for_chunks(v)
            elif isinstance(obj, list):
                for el in obj:
                    found += scan_for_chunks(el)
            return found
        try:
            if isinstance(raw, dict):
                raw_chunks = scan_for_chunks(raw)
                for ch in raw_chunks:
                    snippets.append(_normalize_chunk(ch, resp_for_lookup=resp))
        except Exception:
            pass

    # dedupe and return top_n
    seen = set()
    unique = []
    for s in snippets:
        key = ((s.get("doc") or "").strip(), (s.get("text") or "")[:300])
        if key in seen:
            continue
        seen.add(key)
        unique.append(s)
        if len(unique) >= top_n:
            break

    return unique


def extract_text(resp):
    """Safely extract text from any Gemini response structure."""
    if getattr(resp, "text", None):
        return resp.text

    pieces = []

    for attr in ("candidates", "outputs", "output", "generations", "choices"):
        seq = getattr(resp, attr, None)
        if not seq:
            continue
        if not isinstance(seq, (list, tuple)):
            seq = [seq]
        for item in seq:
            # Common text fields
            for f in ("text", "content", "display_text"):
                if hasattr(item, f):
                    val = getattr(item, f)
                    if isinstance(val, str):
                        pieces.append(val)
                    else:
                        pieces.append(str(val))
            # Nested fields
            for sub in ("message", "completion", "result"):
                if hasattr(item, sub):
                    subobj = getattr(item, sub)
                    for f in ("text", "content"):
                        if hasattr(subobj, f):
                            val = getattr(subobj, f)
                            if isinstance(val, str):
                                pieces.append(val)
                            else:
                                pieces.append(str(val))
            pieces.append(str(item))

    raw = getattr(resp, "_raw", None) or getattr(resp, "raw", None)
    if isinstance(raw, dict):
        def scan(obj):
            if isinstance(obj, str):
                return [obj]
            out = []
            if isinstance(obj, dict):
                for k, v in obj.items():
                    out += scan(v)
            elif isinstance(obj, list):
                for el in obj:
                    out += scan(el)
            return out
        raw_text = scan(raw)
        for t in raw_text:
            if t and isinstance(t, str):
                pieces.append(t)

    pieces = [str(p).strip() for p in pieces if p and str(p).strip()]
    if pieces:
        return "\n\n".join(pieces)
    return None


def pretty_doc_name(raw_name: str) -> str:
    """
    Remove leading numeric timestamp + underscore (e.g. 1764340785_),
    replace underscores with spaces, trim extension optionally, and tidy casing.
    """
    if not raw_name:
        return "Unknown document"
    name = raw_name.strip()
    # remove leading digits + underscore(s)
    name = re.sub(r'^\d+_+', '', name)
    # optionally remove folder paths
    name = name.split('/')[-1].split('\\')[-1]
    # replace underscores with spaces, collapse multiple spaces
    name = re.sub(r'[_]+', ' ', name)
    # optionally remove common extensions but keep them if you want
    # keep_ext = True  # set False to strip .pdf/.txt
    keep_ext = True
    if not keep_ext:
        name = re.sub(r'\.(pdf|txt|docx|doc|md|pptx)$', '', name, flags=re.I)
    # trim and title-case lightly
    name = name.strip()
    # if it's all-lower/underscored, make it nicer
    if len(name) <= 60:
        name = name.title()
    return name



def _obj_to_plain(o):
    """Convert SDK/protobuf-like objects to plain Python types for display."""
    # dict-like
    if isinstance(o, dict):
        return {k: _obj_to_plain(v) for k, v in o.items()}
    # lists
    if isinstance(o, (list, tuple)):
        return [_obj_to_plain(x) for x in o]
    # objects with .to_dict() or .dict() (common patterns)
    for fn in ("to_dict", "dict", "as_dict"):
        if hasattr(o, fn) and callable(getattr(o, fn)):
            try:
                return _obj_to_plain(getattr(o, fn)())
            except Exception:
                pass
    # objects with __dict__
    if hasattr(o, "__dict__") and getattr(o, "__dict__"):
        try:
            return _obj_to_plain(vars(o))
        except Exception:
            pass
    # fallback to simple types (int/float/str/bool/None)
    if isinstance(o, (str, int, float, bool)) or o is None:
        return o
    # last resort: string representation
    try:
        return str(o)
    except Exception:
        return repr(o)


def extract_grounding(resp):
    """
    Attempt to extract grounding / retrieval / citation information from a model response.
    Returns a structured dict like:
      { "source": "<where found>", "items": [ ...normalized items... ] }
    or None if nothing reasonable is found.
    """

    # 1) Candidate-level grounding is common: response.candidates[*].grounding_metadata
    try:
        candidates = getattr(resp, "candidates", None)
        if candidates:
            items = []
            for i, cand in enumerate(candidates):
                # try several attribute names that may hold grounding
                gm = (getattr(cand, "grounding_metadata", None)
                      or getattr(cand, "groundingMetadata", None)
                      or getattr(cand, "grounding", None)
                      or getattr(cand, "grounding_chunks", None)
                      or getattr(cand, "retrievals", None)
                      or getattr(cand, "sources", None))
                if gm:
                    items.append({
                        "candidate_index": i,
                        "grounding": _obj_to_plain(gm)
                    })
            if items:
                return {"source": "candidates", "items": items}
    except Exception:
        # don't fail hard on unexpected SDK shapes
        pass

    # 2) Top-level attributes on the response object
    for attr in ("grounding_metadata", "grounding", "groundingMetadata", "grounding_chunks", "retrievals", "sources", "citation_metadata"):
        try:
            val = getattr(resp, attr, None)
            if val:
                return {"source": attr, "items": _obj_to_plain(val)}
        except Exception:
            continue

    # 3) Raw dict search (response._raw or response.raw)
    raw = getattr(resp, "_raw", None) or getattr(resp, "raw", None)
    if isinstance(raw, dict):
        # look for keys we care about and return their normalized content
        keys_of_interest = {"grounding", "grounding_metadata", "grounding_chunks", "retrievals", "sources", "citations", "references"}
        def find_keys(obj, path=""):
            found = []
            if isinstance(obj, dict):
                for k, v in obj.items():
                    lk = k.lower()
                    new_path = f"{path}.{k}" if path else k
                    if lk in keys_of_interest:
                        found.append({"path": new_path, "value": _obj_to_plain(v)})
                    # recursive search
                    found.extend(find_keys(v, new_path))
            elif isinstance(obj, list):
                for idx, el in enumerate(obj):
                    found.extend(find_keys(el, f"{path}[{idx}]"))
            return found

        matches = find_keys(raw, "")
        if matches:
            return {"source": "_raw", "items": matches}

    # Nothing found
    return None


def list_filestore_documents(client, file_search_store_name, api_key=None):
    """
    Returns a list of file/document metadata dicts from a File Search store.
    Tries SDK method first; falls back to REST API if needed.
    """
    # Try SDK route (some SDK versions: client.file_search_stores.documents.list)
    try:
        # Many SDKs expose a documents collection under file_search_stores
        docs_iter = client.file_search_stores.documents.list(parent=file_search_store_name)
        # docs_iter may be an iterator/generator — convert to list
        docs = list(docs_iter)
        # Convert SDK objects to plain dicts if possible
        def _plain(o):
            if hasattr(o, "to_dict"):
                try:
                    return o.to_dict()
                except Exception:
                    pass
            if hasattr(o, "dict"):
                try:
                    return o.dict()
                except Exception:
                    pass
            # fallback to __dict__ or str
            if hasattr(o, "__dict__"):
                try:
                    return dict(o.__dict__)
                except Exception:
                    pass
            return {"raw": str(o)}
        plain_docs = [_plain(d) for d in docs]
        return plain_docs
    except Exception as e_sdk:
        # SDK path failed (some versions had a bug). Fall back to REST.
        # Construct REST URL:
        # The REST path is: https://generativelanguage.googleapis.com/v1beta/{parent=fileSearchStores/*}/documents
        # parent should be the full store resource name, e.g. "fileSearchStores/my-store-123"
        if api_key is None:
            raise RuntimeError("SDK failed and no api_key provided for REST fallback. SDK error: " + str(e_sdk))
        url = f"https://generativelanguage.googleapis.com/v1beta/{file_search_store_name}/documents"
        headers = {"Authorization": f"Bearer {api_key}"}  # developer key should work here
        params = {"pageSize": 200}  # adjust if needed
        resp = requests.get(url, headers=headers, params=params, timeout=30)
        if not resp.ok:
            raise RuntimeError(f"REST fallback failed: {resp.status_code} {resp.text}")
        j = resp.json()
        # The REST body commonly returns {'documents': [...]} or similar
