def _extract_page_from_text(text):
    import re
    if not text:
        return None
    m = re.search(r'---\s*PAGE\s*(\d+)\s*---', text, re.I)
    if m:
        return m.group(1)

    m2 = re.search(r'\bpage[\s:]*([0-9]{1,3})\b', text, re.I)
    if m2:
        return m2.group(1)

    return None


